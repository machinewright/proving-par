// Writes src/boards.js: the essay's boards as literals, so the text never drifts from the widgets.
import { writeFileSync } from 'node:fs';
import { generate, generateWith, paramsFor } from '../src/generator.js';
const enc = (g) => {
  const rows = [];
  for (let y = 0; y < g.h; y++) rows.push(g.cells.slice(y * g.w, (y + 1) * g.w).map((c) =>
    c.type === 'empty' ? '.' : c.type === 'wall' ? '#' : c.type === 'target' ? 'o'
    : c.type === 'mirror' ? (c.rot ? '\\' : '/') : c.type === 'emitter' ? '^>v<'[c.dir] : '?').join(''));
  return rows;
};
const p = { ...paramsFor(28), colors: 1, filters: 0, splitters: 0 };
const boards = { hook: generate(147, 4), big: generateWith(40, p), weak: generateWith(41, p) };
let out = '// Generated by proto/freeze.mjs. Board rows: . empty, # wall, o target, / and \\ mirrors, ^>v< emitters.\n';
out += "import { makeGrid } from './engine.js';\n\nexport const BOARDS = {\n";
for (const [k, b] of Object.entries(boards)) out += `  ${k}: { par: ${b.par}, rows: ${JSON.stringify(enc(b.puzzle))} },\n`;
out += `};

export function parseBoard(rows) {
  const g = makeGrid(rows[0].length, rows.length);
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    const c = g.cells[y * g.w + x];
    if (ch === '#') c.type = 'wall';
    else if (ch === 'o') c.type = 'target';
    else if (ch === '/' || ch === '\\\\') { c.type = 'mirror'; c.rot = ch === '/' ? 0 : 1; }
    else if ('^>v<'.includes(ch)) { c.type = 'emitter'; c.dir = '^>v<'.indexOf(ch); }
  }));
  return g;
}

export const board = (name) => parseBoard(BOARDS[name].rows);
`;
writeFileSync(new URL('../src/boards.js', import.meta.url), out);
